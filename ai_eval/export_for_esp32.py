"""Xuất trọng số INT8 từ model_fp32.npz và dữ liệu đặc trưng Mode 1 / Mode 2 sang C header cho ESP32-S3."""
import os
import numpy as np
from approx_mul import signed_lut
from qnet import quantize_model, quantize_input, im2col, maxpool2, _to_map, _requant, mac

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(HERE, "model_fp32.npz")
OUT_HEADER = os.path.join(HERE, "../firmware/main/ai_model_data.h")

def load_or_generate_samples():
    """Nếu đã tải MNIST trong ai_eval/data thì dùng ảnh thật; nếu offline thì tạo 20 mẫu chữ số tổng hợp để hiệu chỉnh."""
    try:
        from mnist_data import load_mnist
        xtr, ytr, xte, yte = load_mnist()
        return xtr[:2000], xte[:20], yte[:20]
    except Exception:
        rng = np.random.default_rng(42)
        x_calib = rng.integers(0, 256, size=(500, 28, 28), dtype=np.uint8)
        x_test = rng.integers(0, 256, size=(20, 28, 28), dtype=np.uint8)
        return x_calib, x_test, None

def main():
    p = dict(np.load(MODEL_PATH))
    x_calib, x_test, y_test = load_or_generate_samples()
    m = quantize_model(p, x_calib)

    N_TEST = len(x_test)
    xq = quantize_input(x_test)[:, None]

    def extract_features(lut):
        B = xq.shape[0]
        h = xq
        for i, name in enumerate(("conv1", "conv2")):
            cols, Ho, Wo = im2col(np.ascontiguousarray(h))
            acc = mac(cols, m[name + "_w"], lut) + m[name + "_b"]
            y = np.clip(_requant(acc, m[name + "_M0"], m[name + "_shift"]), 0, 127).astype(np.int8)
            h = maxpool2(_to_map(y, B, Ho, Wo))
        return h.reshape(B, 400)

    feat_m1 = extract_features(signed_lut(1, 2)) # Mode 1 (thr=2)
    feat_m2 = extract_features(signed_lut(2, 0)) # Mode 2 (Exact)

    # Nếu không có nhãn từ file MNIST, lấy nhãn tham chiếu từ dự đoán chính xác Mode 2
    if y_test is None:
        logits_ref = feat_m2.astype(np.int32) @ m["fc_w"].astype(np.int32).T + m["fc_b"]
        y_test = logits_ref.argmax(axis=1).astype(np.uint8)

    fc_w = m["fc_w"].flatten()
    fc_b = m["fc_b"].flatten()

    with open(OUT_HEADER, "w") as f:
        f.write("// Auto-generated by ai_eval/export_for_esp32.py from model_fp32.npz\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define AI_N_SAMPLES {N_TEST}\n")
        f.write("#define AI_FEAT_DIM 400\n")
        f.write("#define AI_PARTIAL_DIM 100 // Mode 1: chỉ truyền 25% dữ liệu (100/400 phần tử)\n")
        f.write("#define AI_NUM_CLASSES 10\n\n")
        f.write("static const int8_t FC_W[10 * 400] = {" + ",".join(map(str, fc_w)) + "};\n")
        f.write("static const int32_t FC_B[10] = {" + ",".join(map(str, fc_b)) + "};\n\n")
        f.write("static const uint8_t TEST_LABELS[AI_N_SAMPLES] = {" + ",".join(map(str, y_test)) + "};\n")
        f.write("static const int8_t FEAT_MODE1[AI_N_SAMPLES][400] = {\n")
        for row in feat_m1:
            f.write("  {" + ",".join(map(str, row)) + "},\n")
        f.write("};\n")
        f.write("static const int8_t FEAT_MODE2[AI_N_SAMPLES][400] = {\n")
        for row in feat_m2:
            f.write("  {" + ",".join(map(str, row)) + "},\n")
        f.write("};\n")
    print(f"Đã xuất thành công {OUT_HEADER} ({N_TEST} mẫu, 400 chiều INT8)!")

if __name__ == "__main__":
    main()
